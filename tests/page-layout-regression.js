'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../assets/start-page-layout.js'), 'utf8');
const saved = new Map(), disabled = new Set(), events = [];
let failWrites = false;
const context = { window: { RelatumFeatureRuntime: { enabled: id => !disabled.has(id) } },
  localStorage: { getItem: key => saved.get(key) || null, setItem(key, value) { if (failWrites) throw Error('quota'); saved.set(key, value); }, removeItem: key => saved.delete(key) },
  document: { dispatchEvent: event => events.push(event) }, CustomEvent: class { constructor(type, options) { this.type = type; this.detail = options.detail; } } };
vm.runInNewContext(source, context);
const model = context.window.RelatumPageLayout, plain = value => JSON.parse(JSON.stringify(value));
(async () => {
assert.deepEqual(plain(model.layout('daily').order), ['tasks', 'calendar', 'focus', 'ledger', 'images']);
assert.equal(saved.size, 0, 'default reads never persist');
saved.set(model.keys.canvas, JSON.stringify({ order: ['group:b', 'recent', 'review', 'group:a', 'recent', 'invalid'] }));
assert(model.layout('canvas').order.includes('group:b'), 'unknown group identities survive before a successful directory read');
model.setGroups([{ id: 'a', name: 'A' }, { id: 'b', name: 'B' }]);
const before = plain(model.layout('canvas').order);
await model.apply('canvas', { order: before });
assert.deepEqual(before.slice(0, 4), ['group:b', 'recent', 'review', 'group:a']);
model.setGroups([{ id: 'a', name: '改名' }, { id: 'b', name: 'B' }, { id: 'c', name: 'C' }]);
assert.deepEqual(plain(model.layout('canvas').order), [...before, 'group:c'], 'new groups append after an existing customized order');
assert.equal(model.items('canvas').find(item => item.id === 'group:a').label[0], '改名');
disabled.add('canvas.review');
assert.equal(model.items('canvas').some(item => item.id === 'review'), false);
assert.equal(model.layout('canvas').order.indexOf('review'), 2, 'disabled pages retain their slots');
disabled.delete('canvas.review');
model.setGroups([{ id: 'b', name: 'B' }]);
assert.equal(model.layout('canvas').order.some(id => id === 'group:a' || id === 'group:c'), false);
const daily = { order: ['ledger', 'tasks', 'focus', 'calendar', 'images'], hidden: ['focus'] };
assert.equal(await model.apply('daily', daily), true);
assert.deepEqual(plain(model.layout('daily')), daily);
assert.equal(model.items('daily').some(item => item.id === 'focus'), false);
assert.equal(model.items('daily', { includeHidden: true }).some(item => item.id === 'focus'), true);
disabled.add('daily.focus');
assert(model.layout('daily').hidden.includes('focus'), 'disabled pages keep their visibility');
disabled.delete('daily.focus');
const count = events.length;
failWrites = true;
assert.equal(await model.apply('daily', { order: ['focus'] }), false);
assert.equal(events.length, count, 'failed writes do not publish uncommitted order');
assert.deepEqual(plain(model.layout('daily')), daily);
failWrites = false;
await model.apply('daily', null, { reset: true });
assert.equal(saved.has(model.keys.daily), false);
for (const id of ['review', 'recent', 'favorites', 'inbox', 'group:b']) assert.equal(model.routeId(model.route(id)), id);
saved.set(model.keys.daily, '{broken');
assert.deepEqual(plain(model.layout('daily').order), ['tasks', 'calendar', 'focus', 'ledger', 'images']);
saved.set('canvas:hideSpecialPages', '1'); saved.delete(model.keys.canvas);
assert.deepEqual(plain(model.layout('canvas').hidden), ['review', 'cadence', 'notes', 'tree', 'study']);
assert.equal(saved.has(model.keys.canvas), false, 'legacy reads do not write defaults');
disabled.add('canvas.library');
assert.equal(model.layout('canvas').hidden.length, 0, 'legacy bulk hiding was inactive without the library');
disabled.delete('canvas.library');
await model.apply('canvas', { ...plain(model.layout('canvas')), hidden: ['group:b'] });
assert.equal(saved.has('canvas:hideSpecialPages'), false);
assert(model.isVisible('canvas', 'review'));
model.setGroups([{ id: 'b', name: 'Renamed' }, { id: 'c', name: 'New' }]);
assert.equal(model.isVisible('canvas', 'group:b'), false);
assert.equal(model.isVisible('canvas', 'group:c'), true);
await model.apply('canvas', null, { reset: true });
assert.equal(model.layout('canvas').hidden.length, 0);
let release, entered;
const started = new Promise(resolve => entered = resolve), gate = new Promise(resolve => release = resolve), commits = [];
model.configure('daily', async (next, commit) => { commits.push(next.hidden.join(',')); if (commits.length === 1) { entered(); await gate; } return commit(); });
const first = model.apply('daily', { ...daily, hidden: ['tasks'] }); await started;
const second = model.apply('daily', { ...daily, hidden: ['calendar'] });
assert.deepEqual(commits, ['tasks']); release();
assert.deepEqual(await Promise.all([first, second]), [true, true]);
assert.deepEqual(plain(model.layout('daily').hidden), ['calendar']);
model.configure('daily', () => false);
assert.equal(await model.apply('daily', daily), false);
assert.deepEqual(plain(model.layout('daily').hidden), ['calendar'], 'failed handoff never persists');
console.log('Page layout: defaults, identities, visibility, legacy compatibility, serial handoff, write failure and reset passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
