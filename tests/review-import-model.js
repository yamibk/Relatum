'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const model = require('../assets/review-import-model.js');
const XLSX = require('../assets/vendor/sheetjs/xlsx.full.min.js');

const table = model.parseText('\uFEFF单词,释义,例句,卡组,标签\r\n001,"one, first","first\r\nsecond",English,"core,exam"\r\nword,"a ""quoted"" meaning",,,\r\n,,,,\r\n');
assert.equal(table.separator, ',');
assert.equal(table.rows[1].cells[0], '001');
assert.equal(table.rows[1].cells[2], 'first\nsecond');
assert.equal(table.rows[2].sourceRow, 4);
assert.equal(table.rows[2].cells[1], 'a "quoted" meaning');
let config = model.defaults(table);
assert.equal(config.headerRow, 1);
assert.deepEqual(config.answer.columns, [1]);
config.tags = 'common'; config.deckName = 'Default';
let rows = model.mapRows(table, config);
assert.equal(rows.length, 3);
assert.equal(rows[0].deckName, 'English');
assert.equal(rows[1].deckName, 'Default');
assert.deepEqual(rows[0].tags, ['common', 'core', 'exam']);
assert.equal(rows[2].blank, true);
config.answer.columns = [1, 2]; config.answer.labels = true;
assert.equal(model.mapRows(table, config)[0].answer, '释义: one, first  \n例句: first\nsecond');
config.answer.columns.reverse(); config.answer.separator = ' ';
assert.equal(model.mapRows(table, config)[0].answer, '例句: first\nsecond 释义: one, first');
const noHeader = model.parseText('apple\t苹果\nbanana\t香蕉');
assert.equal(model.defaults(noHeader).headerRow, 0);
assert.equal(model.mapRows(noHeader, model.defaults(noHeader))[0].answer, '苹果');
assert.equal(model.parseText('a;b\nword;meaning').separator, ';');
assert.equal(model.parseText('word\tdefinition,with,many,commas\nterm\tone,two,three,four').separator, '\t');
assert.throws(() => model.parseText('a,"not closed'), /unclosed-quote/);
assert.throws(() => model.parseText('a,"closed"oops', ','), /malformed-text/);
assert.throws(() => model.parseText('\n\t\n'), /empty-input/);
assert.equal(model.decode(new Uint8Array([0xd6, 0xd0, 0xce, 0xc4])), '中文');
assert.equal(model.decode(new Uint8Array([0xff, 0xfe, 0x2d, 0x4e, 0x87, 0x65])), '中文');
assert.equal(model.decode(new Uint8Array([0xfe, 0xff, 0x4e, 0x2d, 0x65, 0x87])), '中文');

const book = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet([['word', 'meaning'], ['hidden', '隐藏']]), 'Hidden');
const sheet = XLSX.utils.aoa_to_sheet([['word', 'meaning', 'notes'], ['001', '第一', 'first\nsecond'], [null, '数字', ''], ['formula', '公式', 'unused']]);
sheet.A3 = { t: 'n', v: 7, z: '00000' };
sheet.C4 = { t: 'n', f: '1+1' };
sheet.B5 = { t: 'n', f: '2+2', v: 4 };
sheet.A5 = { t: 's', v: 'cached' };
sheet['!ref'] = 'A1:C5';
XLSX.utils.book_append_sheet(book, sheet, 'Visible');
book.Workbook = { Sheets: [{ Hidden: 1 }, { Hidden: 0 }] };
const bytes = XLSX.write(book, { bookType: 'xlsx', type: 'buffer' });
const sandbox = { TextEncoder, TextDecoder, Uint8Array, ArrayBuffer, console };
sandbox.self = sandbox;
vm.createContext(sandbox);
sandbox.importScripts = filename => vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'assets', filename), 'utf8'), sandbox, { filename });
let response;
sandbox.postMessage = message => { response = message; };
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'assets/review-import-worker.js'), 'utf8'), sandbox);
sandbox.onmessage({ data: { id: 1, bytes: new Uint8Array(bytes), name: 'words.xlsx' } });
assert(!response.error, JSON.stringify(response.error));
assert.equal(response.table.sheet, 'Visible');
assert.equal(response.table.rows[1].cells[0], '001');
assert.equal(response.table.rows[2].cells[0], '00007');
assert.equal(response.table.rows[4].cells[1], '4');
assert.equal(response.table.errors['4:2'], 'formula-cache');
const workbookConfig = model.defaults(response.table);
assert.equal(model.mapRows(response.table, workbookConfig)[2].sourceError, 'formula-cache');
workbookConfig.notes.columns = [];
assert.equal(model.mapRows(response.table, workbookConfig)[2].sourceError, undefined);
sandbox.onmessage({ data: { id: 2, bytes: new Uint8Array(bytes), name: 'words.xlsx', sheet: 'Hidden' } });
assert.equal(response.table.sheet, 'Hidden');
sandbox.onmessage({ data: { id: 3, text: 'word\tmeaning\na\t一', separator: 'auto' } });
assert.equal(response.table.rows[1].cells[1], '一');

const large = model.parseText('word\tmeaning\n' + Array.from({ length: 10000 }, (_, i) => 'w' + i + '\tmeaning ' + i).join('\n'));
const started = performance.now();
assert.equal(model.mapRows(large, model.defaults(large)).length, 10000);
console.log('review import parser, mapping, encodings, and XLSX passed; 10000-row mapping: ' + (performance.now() - started).toFixed(1) + 'ms');
