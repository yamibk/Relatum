'use strict';
const assert = require('node:assert/strict');
const C = require('../assets/image-markup-core.js');
const source = id => ({ id, width: 800, height: 500, blob: { sentinel: id } });
const session = C.createSession(), a = source('a'), b = source('b'), c = source('c');
C.commit(session, C.initial(a));
let scene = C.snapshot(session.scene);
scene.objects.push({ id: 'r', type: 'rect', x: 20, y: 30, w: 100, h: 80, width: 4, color: 'red' });
C.commit(session, scene);
scene.objects[0].x = 999;
assert.equal(session.scene.objects[0].x, 20, 'history owns geometry snapshots');
assert.equal(session.scene.source.blob, a.blob, 'history never clones image bytes');
assert(C.travel(session)); assert.equal(session.scene.objects.length, 0);
assert(C.travel(session, true)); assert.equal(session.scene.objects.length, 1);
C.commit(session, C.initial(b)); C.commit(session, C.initial(c));
assert(session.past.every(item => !item || item.source.id !== 'a'), 'third import releases all references to oldest image');
assert(C.travel(session)); assert.equal(session.scene.source, b);
assert(C.travel(session, true)); assert.equal(session.scene.source, c);
C.commit(session, null); assert.equal(session.scene, null);
assert(C.travel(session)); assert.equal(session.scene.source, c, 'delete is undoable');
assert(C.travel(session, true)); assert.equal(session.scene, null);
C.commit(session, C.initial(a));
assert(!session.past.some(item => item?.source.id === 'b'));
for (let i = 0; i < 140; i++) C.commit(session, C.initial(a));
assert.equal(session.past.length, C.LIMITS.history);
assert.equal(session.future.length, 0);
const rect = { id: 'r', type: 'rect', x: 10, y: 20, w: 80, h: 60, width: 4 };
assert.deepEqual(C.bounds(C.moved(rect, 20, -10)), { x: 30, y: 10, w: 80, h: 60 });
assert(C.hit(rect, { x: 40, y: 40 }, 0)); assert(!C.hit(rect, { x: 200, y: 40 }, 2));
const line = { type: 'line', x: 80, y: 90, x2: 20, y2: 30, width: 3 };
assert(C.hit(line, { x: 50, y: 60 }, 1)); assert(!C.hit(line, { x: 50, y: 80 }, 1));
const scaled = C.resized(line, { x: 0, y: 0, w: 100, h: 200 });
assert.equal(scaled.x, 100); assert.equal(scaled.y, 200); assert.equal(scaled.x2, 0); assert.equal(scaled.y2, 0);
const pen = { type: 'pen', width: 2, points: [{ x: 10, y: 20 }, { x: 50, y: 60 }] };
assert(C.hit(pen, { x: 30, y: 40 }, 2)); assert(!C.hit(pen, { x: 30, y: 60 }, 2));
assert.deepEqual(C.bounds(C.resized(pen, { x: 20, y: 40, w: 80, h: 100 })), { x: 20, y: 40, w: 80, h: 100 });
assert.equal(C.pick([{ ...rect, id: 'first' }, { ...rect, id: 'last' }], { x: 40, y: 40 }, 0).id, 'last');
assert.deepEqual(C.cropRect({ x: -10.5, y: 9.2, w: 40, h: 900 }, a), { x: 0, y: 9, w: 30, h: 491 });
assert.deepEqual(C.cropRect({ x: 900, y: 10, w: 20, h: 10 }, a), { x: 800, y: 10, w: 0, h: 10 });
assert(C.dimensionsValid(8192, 8192)); assert(!C.dimensionsValid(8193, 8193)); assert(!C.dimensionsValid(16385, 1));
assert(!C.dimensionsValid(0, 20)); assert(!C.dimensionsValid(20.5, 20));
const png = new ArrayBuffer(24), bytes = new Uint8Array(png), data = new DataView(png);
Buffer.from('\x89PNG\r\n\x1a\n', 'latin1').copy(Buffer.from(bytes.buffer)); Buffer.from('IHDR').copy(Buffer.from(bytes.buffer), 12);
data.setUint32(16, 640); data.setUint32(20, 480);
assert.deepEqual(C.imageHeader(png), { media: 'image/png', width: 640, height: 480 });
assert.equal(C.imageHeader(new ArrayBuffer(3)), null);
const bmp = new ArrayBuffer(26), bmpView = new DataView(bmp); new Uint8Array(bmp).set([66, 77]);
bmpView.setUint32(14, 40, true); bmpView.setInt32(18, 12, true); bmpView.setInt32(22, -8, true);
assert.deepEqual(C.imageHeader(bmp), { media: 'image/bmp', width: 12, height: 8 });
const text = { text: 'ab\n中文', size: 20, w: 15 };
assert.deepEqual(C.textLines({ measureText: s => ({ width: [...s].length * 10 }) }, text), ['a', 'b', '中', '文']);
console.log('Image markup core: session/history, image budgets, geometry, hit tests and text passed.');
